    public function run(): void
    {
        DB::transaction(function () {
            $own = CatalogSupplier::firstOrCreate(['code' => 'promolux'], ['name' => 'Promolux — собственное производство']);
            $partner = CatalogSupplier::firstOrCreate(['code' => 'sfp'], ['name' => 'SFP — партнёрское производство']);
            $tech = $this->dictionary(CatalogTechnology::class, ['wide' => 'Широкоформатная печать', 'plot' => 'Плоттерная резка', 'inkjet' => 'Струйная печать', 'cut' => 'Резка бумаги', 'uv' => 'УФ-печать (SFP)']);
            $equipment = $this->dictionary(CatalogEquipment::class, ['wide' => 'Широкоформатный принтер', 'plot' => 'Режущий плоттер / каттер', 'inkjet' => 'Струйный принтер для визиток', 'cut' => 'Оборудование для резки отпечатанных визиток']);
            $number = 0;
            $group = 0;
            foreach (self::GROUPS as $category => $names) {
                $group++;
                $parent = CatalogCategory::firstOrCreate(['code' => sprintf('cat-%02d', $group)], ['name' => $category, 'sort' => $group]);
                foreach ($names as $name) {
                    $number++;
                    $design = $group === 13;
                    $active = $design || in_array($number, [1, 2, 37, 38], true);
                    $technology = [1 => 'inkjet', 2 => 'uv', 37 => 'plot', 38 => 'wide'][$number] ?? null;
                    CatalogProduct::firstOrCreate(['code' => sprintf('pl-%03d', $number)], [
                        'category_id' => $parent->id, 'name' => $name, 'sort' => $number,
                        'type' => $design || $number === 63 ? 'service' : ($group === 12 || $number === 37 ? 'work' : 'product'),
                        'unit' => $number === 38 ? 'м²' : ($design || $number === 63 ? 'услуга' : ($number === 37 ? 'пог. м' : 'шт.')),
                        'active' => $active, 'area_pricing' => $number === 38,
                        'supplier_id' => $active ? ($number === 2 ? $partner->id : $own->id) : null,
                        'alternative_ids' => $design ? [$partner->id] : [],
                        'technology_id' => $tech[$technology] ?? null,
                        'equipment_ids' => match ($number) {
                            1 => [$equipment['inkjet'], $equipment['cut']], 37 => [$equipment['plot']], 38 => [$equipment['wide']], default => [],
                        },
                        'fields' => match ($group) {
                            1 => ['Размер', 'Бумага', 'Плотность', 'Количество сторон', 'Ламинация', 'Отделка'],
                            2 => ['Формат', 'Бумага', 'Плотность', 'Цветность', 'Количество сторон'],
                            3 => ['Формат', 'Количество страниц', 'Бумага блока', 'Обложка', 'Тип скрепления'],
                            7 => ['Материал', 'Обработка краёв'],
                            13 => ['Вид услуги', 'Количество страниц или проектов', 'Описание требований'],
                            default => [],
                        },
                    ]);
                }
            }
        });
    }

    private function dictionary(string $model, array $names): array
    {
        $ids = [];
        foreach ($names as $code => $name) {
            $ids[$code] = $model::firstOrCreate(['code' => $code], ['name' => $name])->id;
        }

        return $ids;
    }
